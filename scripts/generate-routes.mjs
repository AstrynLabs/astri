import { readFile, writeFile } from 'node:fs/promises';

const SPEC_URL = 'https://raw.githubusercontent.com/discord/discord-api-spec/main/specs/openapi.json';
const OUTPUT = new URL('../lib/constants/routes.ts', import.meta.url);
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const OVERRIDES = {
    '/channels/{channel_id}/messages/{message_id}/reactions/{emoji_name}/@me': 'channelMessageOwnReaction',
    '/channels/{channel_id}/messages/{message_id}/reactions/{emoji_name}/{user_id}': 'channelMessageUserReaction',
    '/channels/{channel_id}/users/@me/threads/archived/private': 'channelJoinedPrivateArchivedThreads',
    '/channels/{channel_id}/threads/archived/private': 'channelPrivateArchivedThreads',
    '/channels/{channel_id}/threads/archived/public': 'channelPublicArchivedThreads',
    '/guilds/{guild_id}/scheduled-events/{guild_scheduled_event_id}/{guild_scheduled_event_exception_id}/users': 'guildScheduledEventExceptionUsers',
    '/guilds/templates/{code}': 'template',
    '/interactions/{interaction_id}/{interaction_token}/callback': 'interactionCallback',
    '/oauth2/@me': 'oauth2CurrentAuthorization',
    '/partner-sdk/dms/{user_id_1}/{user_id_2}/messages/{message_id}/moderation-metadata': 'partnerSdkDmMessageModerationMetadata',
    '/webhooks/{webhook_id}/{webhook_token}/messages/@original': 'webhookTokenOriginalMessage'
};

const camel = (segment) => segment.replace(/[-.](\w)/g, (_, char) => char.toUpperCase());
const capitalize = (word) => word.charAt(0).toUpperCase() + word.slice(1);
const singular = (word) => (word.endsWith('ies') ? `${word.slice(0, -3)}y` : word.endsWith('ss') ? word : word.replace(/s$/, ''));

function routeName(route) {
    if (OVERRIDES[route] !== undefined) return OVERRIDES[route];
    const parts = [];
    let previous = null;
    for (const segment of route.split('/').slice(1)) {
        const param = segment.match(/^\{(\w+)\}$/);
        if (param !== null) {
            if (previous?.kind === 'static') parts[parts.length - 1] = singular(parts.at(-1));
            else if (previous?.kind === 'param')
                parts.push(
                    camel(
                        param[1]
                            .replace(/_id$/, '')
                            .replace(`${previous.name.replace(/_id$/, '')}_`, '')
                            .replace(/_/g, '-')
                    )
                );
            previous = { kind: 'param', name: param[1] };
        } else if (segment === '@me') {
            parts[parts.length - 1] = `current${capitalize(singular(parts.at(-1)))}`;
            previous = { kind: 'me' };
        } else {
            parts.push(camel(segment));
            previous = { kind: 'static' };
        }
    }
    return parts.map((part, index) => (index === 0 ? part : capitalize(part))).join('');
}

const spec = process.argv[2] === undefined ? await (await fetch(SPEC_URL)).json() : JSON.parse(await readFile(process.argv[2], 'utf8'));
const routes = {};
for (const [route, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
        const operation = item[method];
        if (operation === undefined) continue;
        const hasQuery = [...(item.parameters ?? []), ...(operation.parameters ?? [])].some((parameter) => parameter.in === 'query');
        const data = operation.requestBody !== undefined ? 'body' : hasQuery ? 'query' : null;
        const isCreate = method === 'post' && /\/[\w-]+s$/.test(route) && Object.keys(spec.paths).some((other) => other.startsWith(`${route}/{`));
        const name = isCreate ? singular(routeName(route)) : routeName(route);
        routes[name] ??= {};
        if (routes[name][method] !== undefined) throw new Error(`${method.toUpperCase()} ${name} is both ${routes[name][method].route} and ${route}`);
        routes[name][method] = { route, data };
    }
}

const entries = Object.entries(routes)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
        ([name, methods]) =>
            `    ${name}: { ${Object.entries(methods)
                .map(([method, { route, data }]) => `${method}: { route: '${route}', data: ${data === null ? 'null' : `'${data}'`} }`)
                .join(', ')} }`
    );

await writeFile(
    OUTPUT,
    `/**
 * This file was auto-generated by scripts/generate-routes.mjs from Discord's OpenAPI spec.
 * Do not make direct changes to the file.
 */

/**
 * Every REST route by name, then by method. \`data\` says what the argument after the path parameters is:
 * the request body, the query string, or nothing.
 */
export const RESTRoutes = {
${entries.join(',\n')}
} as const;
`
);
console.log(`Wrote ${Object.keys(routes).length} route names`);
